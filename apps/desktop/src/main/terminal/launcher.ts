/**
 * DevHub's own files on a machine it is not running on: the `devhub` command's
 * shim and where it, the forwarded control socket and the `/devhub` skill go
 * (`RemoteShellRuntime.terminalLauncher`).
 */

import { createHash } from "node:crypto";
import { posix } from "node:path";
import type { ShellMachineId } from "../runtime/runtime.js";
import { shellQuote } from "../runtime/quote.js";

/**
 * The `devhub` command DevHub puts on a host: a shim on the pane's PATH that
 * runs the app's own Go binary installed there (`ToolDelivery` `devhub`,
 * `docs/devhub-cli.md`), speaking DevHub's control protocol over the socket
 * that is reverse-forwarded onto the host. One front door and one protocol,
 * which is the thing `../cli/protocol.ts` opens by saying.
 */
export const REMOTE_CLI_NAME = "devhub";

/** Where the shim goes, under the tagged directory this DevHub owns there. */
export const REMOTE_CLI_DIRECTORY_PREFIX = "bin";

/**
 * The `devhub` a pane on another machine runs.
 *
 * Generated because it records the absolute facts the binary cannot discover
 * on its own — which install of it is this DevHub's, and the socket DevHub is
 * answering on over there. Written rather than exported through the
 * environment, because `DEVHUB_*` is a family a terminal is not supposed to
 * inherit.
 *
 * `DEVHUB_MACHINE` is the one thing this says that the local launcher does not
 * have to: it is which computer the paths typed into this pane are paths on,
 * and without it DevHub would match a host's `/srv/app` against a Workspace of
 * the same name here. There is no `DEVHUB_LAUNCH_COMMAND`, and its absence is
 * the truth rather than an omission — DevHub runs on the machine the window is
 * on, and nothing over here can start it.
 */
export function remoteCliScript(request: {
	/** The installed `devhub` binary on that machine. */
	readonly execPath: string;
	readonly socketPath: string;
	readonly machine: ShellMachineId;
}): string {
	return [
		"#!/bin/sh",
		"# Generated by DevHub on startup — do not edit, and do not copy.",
		"#",
		"# The paths below name one running DevHub, on the machine its window is",
		"# on, reached over a socket forwarded onto this one. They are rewritten",
		"# every time that DevHub starts.",
		`if [ ! -x ${shellQuote(request.execPath)} ]; then`,
		`\techo ${shellQuote(`devhub: ${request.execPath} is not there to run, so there is nothing here that can reach DevHub.`)} >&2`,
		"\texit 1",
		"fi",
		`DEVHUB_CONTROL_SOCKET=${shellQuote(request.socketPath)} \\`,
		`DEVHUB_MACHINE=${shellQuote(request.machine)} \\`,
		`exec ${shellQuote(request.execPath)} "$@"`,
		"",
	].join("\n");
}

/**
 * The directory DevHub owns on a machine that is not the one it runs on.
 *
 * `~/.devhub/terminal`, where it has always been, so a host DevHub reached
 * before keeps one directory of DevHub's rather than two.
 */
export const REMOTE_DEVHUB_DIRECTORY = ".devhub/terminal";

/**
 * What the far machine's copy of the program is filed under.
 *
 * Named after the socket rather than after the host, because what must not
 * collide is two DevHubs — two profiles on this Mac, reaching one host — and
 * the socket path is the one thing that already distinguishes them. A digest
 * and not the path itself: the path is this Mac's business and long, and the
 * far machine only needs it to be different.
 */
export function remoteProfileTag(controlSocketPath: string): string {
	return createHash("sha256")
		.update(controlSocketPath)
		.digest("hex")
		.slice(0, 12);
}

/** Every path DevHub writes on a machine it is not running on. */
export interface RemoteTerminalPaths {
	/** `~/.devhub/terminal` — the one directory DevHub owns there. */
	readonly directory: string;
	/** Where DevHub's control socket is forwarded to. */
	readonly socket: string;
	/** The directory the `devhub` shim is in, and the one added to the pane PATH. */
	readonly cliBinDirectory: string;
	/** The shim itself. */
	readonly cli: string;
	/**
	 * The `/devhub` skill's root for Agents on that machine — the directory
	 * Claude's `--add-dir=` names; the SKILL.md is under
	 * `.claude/skills/devhub/`. Tagged like the bin directory, because the
	 * skill names that DevHub's `devhub` by its full path.
	 */
	readonly skillRoot: string;
	/** The SKILL.md itself. */
	readonly skillFile: string;
}

/** Where all of it goes on the far machine, from its `$HOME` and the control socket's tag. */
export function remoteTerminalPaths(request: {
	readonly home: string;
	readonly controlSocketPath: string;
}): RemoteTerminalPaths {
	const directory = posix.join(request.home, REMOTE_DEVHUB_DIRECTORY);
	const tag = remoteProfileTag(request.controlSocketPath);
	const skillRoot = posix.join(directory, `skill-${tag}`);
	const cliBinDirectory = remoteCliBinDirectory(
		request.home,
		request.controlSocketPath,
	);
	return {
		directory,
		skillRoot,
		skillFile: posix.join(skillRoot, ".claude", "skills", "devhub", "SKILL.md"),
		socket: posix.join(directory, `control-${tag}.sock`),
		cliBinDirectory,
		cli: posix.join(cliBinDirectory, REMOTE_CLI_NAME),
	};
}

/**
 * The directory the `devhub` shim goes in on a machine DevHub is not running on.
 *
 * A *directory* per DevHub and not a shared `bin`, because the whole directory
 * is what goes on a pane's PATH: two DevHub profiles reaching one host would
 * otherwise put two `devhub` scripts at one path, and the second to start would
 * take the first's name. Tagged by the control socket, like everything else
 * under this directory, for exactly that reason (`remoteProfileTag`).
 *
 * Derived from two facts a machine can be asked for long before the shim
 * exists, so the PATH entry can be stated when a session is created rather than
 * waiting on a file being written.
 */
export function remoteCliBinDirectory(
	home: string,
	controlSocketPath: string,
): string {
	return posix.join(
		home,
		REMOTE_DEVHUB_DIRECTORY,
		`${REMOTE_CLI_DIRECTORY_PREFIX}-${remoteProfileTag(controlSocketPath)}`,
	);
}
