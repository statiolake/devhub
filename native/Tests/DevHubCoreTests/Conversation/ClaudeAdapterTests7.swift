import XCTest
@testable import DevHubCore

private let IMAGE = ImageRef(mediaType: "image/png", source: .data(base64: PNG), label: "shot.png")
private let PNG_BLOCK: JsonValue = ["type": "image", "source": ["type": "base64", "media_type": "image/png", "data": .string(PNG)]]

final class ClaudeImagesTests: XCTestCase {
    func testAreOnTheMessagesEntryWithItsWordsWhenTheCLIEchoesIt() throws {
        let adapter = ClaudeAdapter(bootId: "boot")
        _ = try adapter.received(initLine())
        try carryOut(adapter, send("what is this?"))
        _ = try adapter.received(
            json([
                "type": "user",
                "message": ["role": "user", "content": [PNG_BLOCK, ["type": "text", "text": "what is this?"]]],
                "parent_tool_use_id": .null, "session_id": .string(SESSION), "uuid": "u-img",
            ]))
        let user = try XCTUnwrap(try entry(adapter, "user:u-img").userEntry)
        XCTAssertEqual(user.text, "what is this?")
        XCTAssertEqual(user.images.map(\.mediaType), ["image/png"])
        XCTAssertEqual(user.images.map(\.source), [.data(base64: PNG)])
        XCTAssertEqual(adapter.transcript.sending, [])
    }

    func testAreWrittenAsImageBlocksBeforeTheWords() throws {
        let adapter = ClaudeAdapter(bootId: "boot")
        _ = try adapter.received(initLine())
        let line = try carryOut(adapter, send("what is this?", images: [IMAGE]))[0]
        let written = parsed([line])[0]
        XCTAssertEqual(written["type"], "user")
        XCTAssertEqual(written["message"], ["role": "user", "content": [PNG_BLOCK, ["type": "text", "text": "what is this?"]]])
        // What was written is what it is known by: the API's block names no file.
        var known = IMAGE
        known.label = "image"
        XCTAssertEqual(
            adapter.transcript.sending, [SendingMessage(id: "sent:1", text: "what is this?", images: [known], origin: .person)])
        _ = try adapter.received(
            json([
                "type": "user", "message": try XCTUnwrap(written["message"]), "parent_tool_use_id": .null,
                "session_id": .string(SESSION), "uuid": "u-img",
            ]))
        XCTAssertEqual(adapter.transcript.sending, [])
        let user = try XCTUnwrap(try entry(adapter, "user:u-img").userEntry)
        XCTAssertEqual(user.text, "what is this?")
        XCTAssertEqual(user.images.map(\.source), [.data(base64: PNG)])
    }

    func testCanBeSentWithoutWords() throws {
        let adapter = ClaudeAdapter(bootId: "boot")
        _ = try adapter.received(initLine())
        let line = try carryOut(adapter, send("", images: [IMAGE]))[0]
        XCTAssertEqual(parsed([line])[0]["message"]?["content"], [PNG_BLOCK])
    }

    func testAreRefusedWhenTheImageIsNotItsOwnBytes() throws {
        let adapter = ClaudeAdapter(bootId: "boot")
        _ = try adapter.received(initLine())
        assertThrows(
            try adapter.encode(
                send("x", images: [ImageRef(mediaType: "image/png", source: .file(path: "/a.png"), label: "/a.png")])),
            "only an image's own bytes")
    }
}

