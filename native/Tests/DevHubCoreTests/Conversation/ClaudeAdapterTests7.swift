final class ClaudeSlashCommandTests: XCTestCase {
    /// A user record of a session file, as `devhub_history` carries it.
    func past(_ uuid: String, _ content: String) -> String {
        json([
            "type": "devhub_history",
            "record": ["type": "user", "uuid": .string(uuid), "message": ["role": "user", "content": .string(content)]],
        ])
    }

    func commands(_ adapter: ClaudeAdapter) -> [CommandEntry] { adapter.transcript.entries.compactMap(\.commandEntry) }

    func testIsOneCompactEntryWithTheCaveatLeftOut() throws {
        let adapter = ClaudeAdapter(bootId: "boot")
        _ = try adapter.received(
            past(
                "u1",
                "<local-command-caveat>Caveat: the messages below were generated by the user while running local commands.</local-command-caveat>"
            ))
        _ = try adapter.received(
            past(
                "u2",
                "<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args>sonnet</command-args>"
            ))
        _ = try adapter.received(past("u3", "<local-command-stdout>Set model to \u{1b}[1msonnet\u{1b}[22m</local-command-stdout>"))
        XCTAssertEqual(
            adapter.transcript.entries,
            [.command(CommandEntry(id: "command:u2", line: "/model sonnet", output: "Set model to sonnet", failed: false))])
    }

    func testSaysACommandsErrorAsFailedAndAShellModeCommandTheSameWay() throws {
        let adapter = ClaudeAdapter(bootId: "boot")
        _ = try adapter.received(past("u1", "<command-name>/nope</command-name>\n<command-args></command-args>"))
        _ = try adapter.received(past("u2", "<local-command-stderr>Unknown command: /nope</local-command-stderr>"))
        _ = try adapter.received(past("u3", "<bash-input>ls src</bash-input>"))
        _ = try adapter.received(past("u4", "<bash-stdout>main.ts</bash-stdout><bash-stderr></bash-stderr>"))
        XCTAssertEqual(
            commands(adapter),
            [
                CommandEntry(id: "command:u1", line: "/nope", output: "Unknown command: /nope", failed: true),
                CommandEntry(id: "command:u3", line: "! ls src", output: "main.ts", failed: false),
            ])
    }

    func testIsOutputAloneWhenNothingSaidWhichCommandPrintedIt() throws {
        let adapter = ClaudeAdapter(bootId: "boot")
        _ = try adapter.received(past("u1", "<local-command-stdout>Compacted.</local-command-stdout>"))
        XCTAssertEqual(commands(adapter), [CommandEntry(id: "command:u1", line: nil, output: "Compacted.", failed: false)])
    }

    func testTakesTheEchoOfACommandDevHubSentAsThatCommand() throws {
        let adapter = ClaudeAdapter(bootId: "boot")
        _ = try adapter.received(initLine())
        try carryOut(adapter, send("/review 12", .injection))
        _ = try adapter.received(
            echo(
                "<command-name>/review</command-name>\n<command-message>review</command-message>\n<command-args>12</command-args>",
                "u-cmd"))
        XCTAssertEqual(adapter.transcript.sending, [])
        XCTAssertEqual(commands(adapter), [CommandEntry(id: "command:u-cmd", line: "/review 12", output: nil, failed: false)])
        XCTAssertEqual(adapter.transcript.entries.filter { $0.kind == "notice" }, [])
    }

    func testTakesTheEchoOfACommandSentWithSpacesAndANewline() throws {
        let adapter = ClaudeAdapter(bootId: "boot")
        _ = try adapter.received(initLine())
        try carryOut(adapter, send("/review   12\n", .injection))
        _ = try adapter.received(
            echo(
                "<command-name>/review</command-name>\n<command-message>review</command-message>\n<command-args>12</command-args>",
                "u-cmd"))
        XCTAssertEqual(adapter.transcript.sending, [])
        XCTAssertEqual(commands(adapter).map(\.line), ["/review 12"])
    }

    func testIsACommandTheCLIAnsweredItselfInPlace() throws {
        let adapter = ClaudeAdapter(bootId: "boot")
        var statuses: [ConversationAgentStatus] = []
        for each in fixture("claude-local-command.handwritten.ndjson") {
            if each.side == .sent { _ = try adapter.sent(each.line) } else { _ = try adapter.received(each.line) }
            statuses.append(conversationStatus(adapter.transcript))
        }
        XCTAssertEqual(adapter.transcript.sending, [])
        let drawn: [[String?]] = adapter.transcript.entries.filter { $0.kind != "turn-end" }.map { each in
            switch each {
            case .command(let command): return ["command", command.line, command.output]
            case .user(let user): return ["user", user.text, user.origin.rawValue]
            default: return [each.kind]
            }
        }
        XCTAssertEqual(
            drawn,
            [
                ["command", "/mcp reconnect", "Reconnecting is not available here."], ["user", "What changed?", "person"],
                ["assistant"], ["command", "/mcp", "2 MCP servers."],
            ])
        // Working from each send until its result, idle again after it.
        XCTAssertEqual(
            statuses,
            [.unknown, .idle, .idle] + [.working, .working, .working, .idle] + [.working, .working, .working, .working, .idle]
                + [.working, .working, .working, .idle])
    }

    func testSaysALocalCommandsErrorAsFailed() throws {
        let adapter = ClaudeAdapter(bootId: "boot")
        _ = try adapter.received(initLine())
        try carryOut(adapter, send("/mcp nope"))
        _ = try adapter.received(
            assistantLine(
                "00000000-0000-4000-8000-0000000000e1", [["type": "text", "text": "Unknown subcommand."]], nil,
                [
                    "uuid": "u-local", "local_command_run": ["command": "mcp", "args": "nope"],
                    "local_command_source": "<local-command-stderr>Unknown subcommand.</local-command-stderr>",
                ]))
        XCTAssertEqual(adapter.transcript.sending, [])
        XCTAssertEqual(
            commands(adapter), [CommandEntry(id: "command:u-local", line: "/mcp nope", output: "Unknown subcommand.", failed: true)])
    }
}
