#!/usr/bin/env python3
"""VS Code's registered colour defaults, as the native DevHub resolves a theme
with them.

The TS app generates its table from the pinned VS Code submodule's colour
registry (`apps/desktop/scripts/generate-color-defaults.mjs`, which runs the
registry modules) into `apps/desktop/src/model/colorDefaults.generated.ts`,
checked in. This script converts that checked-in table into
`native/Sources/DevHubCore/Theme/ColorDefaults.generated.swift`, also checked
in, so the native app needs neither VS Code nor any JavaScript at build or run
time, and both apps resolve every theme from the very same defaults.

Keeping it in sync, after a VS Code bump (or a colour added to
`model/colorIds.ts` / `ColorIds` in `ColorTheme.swift`):

    node apps/desktop/scripts/generate-color-defaults.mjs   # TS table
    python3 native/Scripts/convert-color-defaults.py        # this one
    python3 native/Scripts/convert-color-defaults.py --check  # fail if stale

`ColorDefaultsTests` fails while a colour `ColorIds` names is missing from the
table.
"""

import json
import re
import sys
from pathlib import Path

NATIVE = Path(__file__).resolve().parent.parent
REPO = NATIVE.parent
SOURCE = REPO / "apps" / "desktop" / "src" / "model" / "colorDefaults.generated.ts"
OUTPUT = NATIVE / "Sources" / "DevHubCore" / "Theme" / "ColorDefaults.generated.swift"
THEME_TYPES = ["light", "dark", "hcDark", "hcLight"]


def read_table(text):
    """The object literal after `COLOR_DEFAULTS ... =`, as JSON."""
    start = text.index("= {", text.index("COLOR_DEFAULTS")) + 2
    end = text.rindex("};") + 1
    literal = text[start:end]
    # Bare keys (`light:`, `op:`) quoted; the strings in the table are colour
    # literals and ids, which hold no colon, so this cannot touch a value.
    literal = re.sub(r'([{,]\s*)([A-Za-z_$][\w$]*)\s*:', r'\1"\2":', literal)
    literal = re.sub(r",(\s*[}\]])", r"\1", literal)
    return json.loads(literal)


def number(value):
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"not a number: {value!r}")
    return repr(float(value)) if isinstance(value, float) else str(value)


def swift_string(text):
    return json.dumps(text)


def value(data):
    if data is None:
        return ".none"
    if isinstance(data, str):
        return f".hex({swift_string(data)})" if data.startswith("#") else f".ref({swift_string(data)})"
    if "rgba" in data:
        r, g, b, a = data["rgba"]
        return f".rgba({number(r)}, {number(g)}, {number(b)}, {number(a)})"
    op = data["op"]
    if op in ("darken", "lighten", "transparent"):
        return f".{op}({value(data['value'])}, factor: {number(data['factor'])})"
    if op == "opaque":
        return f".opaque({value(data['value'])}, background: {value(data['background'])})"
    if op == "oneOf":
        return ".oneOf([" + ", ".join(value(one) for one in data["values"]) + "])"
    if op == "lessProminent":
        return (
            f".lessProminent({value(data['value'])}, background: {value(data['background'])}, "
            f"factor: {number(data['factor'])}, transparency: {number(data['transparency'])})"
        )
    if op == "ifDefinedThenElse":
        return (
            f".ifDefinedThenElse({swift_string(data['if'])}, then: {value(data['then'])}, "
            f"else: {value(data['else'])})"
        )
    if op == "mix":
        ratio = number(data["ratio"]) if "ratio" in data else "nil"
        return f".mix({value(data['color'])}, with: {value(data['with'])}, ratio: {ratio})"
    raise ValueError(f"unknown colour transform {op!r}")


def generate(table):
    lines = [
        "// Generated by native/Scripts/convert-color-defaults.py from",
        "// apps/desktop/src/model/colorDefaults.generated.ts, which the TS app generates",
        "// from VS Code's colour registry (the vscode submodule). Do not edit by hand.",
        "",
        "extension ColorDefaults {",
        "    /// VS Code's registered default of every colour DevHub resolves, and of",
        "    /// every colour those defaults refer to, per theme type.",
        "    public static let table: ColorDefaultsTable = [",
    ]
    for color_id in sorted(table):
        per_type = table[color_id]
        lines.append(f"        {swift_string(color_id)}: [")
        for theme_type in THEME_TYPES:
            lines.append(f"            .{theme_type}: {value(per_type[theme_type])},")
        lines.append("        ],")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main(argv):
    text = generate(read_table(SOURCE.read_text(encoding="utf-8")))
    if "--check" in argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(
                f"{OUTPUT.relative_to(REPO)} is stale: run python3 native/Scripts/convert-color-defaults.py",
                file=sys.stderr,
            )
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
