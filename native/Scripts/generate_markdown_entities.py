#!/usr/bin/env python3
"""Writes Sources/DevHubCore/Markdown/MarkdownEntities.generated.swift.

The HTML named character references micromark decodes (the
`character-entities` package's map, MIT, read as data from the TS app's
node_modules): one line per name, as the name and its code points in hex.

    python3 native/Scripts/generate_markdown_entities.py \
        node_modules/.pnpm/character-entities@2.0.2/node_modules/character-entities/index.js
"""
import re
import sys
from pathlib import Path

source = Path(sys.argv[1]).read_text(encoding="utf-8")
pairs = re.findall(r"^\s+'?([A-Za-z0-9]+)'?: '((?:[^'\\]|\\.)*)',?$", source, re.M)
pairs += re.findall(r'^\s+([A-Za-z0-9]+): "([^"]*)",?$', source, re.M)
pairs.sort(key=lambda pair: pair[0])
lines = []
for name, value in pairs:
    value = value.encode("utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8") if "\\" in value else value
    lines.append(name + " " + " ".join("%x" % ord(c) for c in value))
out = Path(__file__).resolve().parent.parent / "Sources/DevHubCore/Markdown/MarkdownEntities.generated.swift"
body = "\n".join(lines)
out.write_text(
    "// Generated by native/Scripts/generate_markdown_entities.py from the\n"
    "// `character-entities` package (MIT): the named character references\n"
    "// micromark decodes. Do not edit.\n\n"
    "enum MarkdownEntities {\n"
    "    /// One line per name: the name, then its code points in hex.\n"
    "    static let table = \"\"\"\n" + body + "\n\"\"\"\n}\n",
    encoding="utf-8",
)
print(len(lines), "entities")
