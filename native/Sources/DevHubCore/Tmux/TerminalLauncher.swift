// Port of the pure parts of apps/desktop/src/main/terminal/launcher.ts and
// main/terminal/devhubTerminal.ts (T-13).
//
// The TS app needs a `devhub-terminal` launcher only because a VS Code
// workbench's integrated terminal is a client DevHub does not start: it runs
// this script, which asks DevHub over the control socket (`terminal-profile`)
// for the argv that attaches to a session and `exec`s it. No session DevHub
// creates references the launcher — sessions run the login shell or an Agent's
// command — so a session made by the TS app is attached by the native app
// unchanged, and the reverse.
//
// The native app has no workbench, so it writes no launcher of its own. What
// is ported is the part that is still a contract: the script text (so a
// launcher a TS DevHub wrote is understood), the one-line command a
// `terminal-profile` answer is printed as, the directory rules a request is
// resolved by, and the names DevHub owns on a remote machine.

import Foundation

public enum TerminalLauncher {
    /// The launcher's file name, next to the control socket it talks to.
    public static let launcherName = "devhub-terminal"

    /// The variable the launcher tells the asking program which machine it is
    /// on with.
    public static let machineVariable = "DEVHUB_TERMINAL_MACHINE"

    /// The `devhub` command DevHub puts on a host.
    public static let remoteCliName = "devhub"
    /// Where the shim goes, under the tagged directory this DevHub owns there.
    public static let remoteCliDirectoryPrefix = "bin"
    /// The directory DevHub owns on a machine that is not the one it runs on.
    public static let remoteDevhubDirectory = ".devhub/terminal"
    /// Where the asking program goes on such a machine.
    public static let remoteEntryDirectory = "js"

    /// The script a workbench terminal runs (`terminalLauncherScript`).
    public static func script(execPath: String, entryScript: String, socketPath: String, machine: String) -> String {
        [
            "#!/bin/sh",
            "# Generated by DevHub on startup — do not edit, and do not copy.",
            "#",
            "# The three paths below name one running DevHub. They are rewritten every",
            "# time it starts, which is why moving or updating the app needs nothing",
            "# done to this file, and why a copy of it is a launcher for a DevHub that",
            "# may no longer be there.",
            "#",
            "# Ask DevHub for the argv, then *become* it. The asking is a child, so",
            "# that Node exits before tmux starts, and what VS Code's pty holds is the",
            "# tmux client itself — the process a hangup has to reach. A tmux client",
            "# that ran as a grandchild would outlive the pty whenever the process in",
            "# between failed to pass the hangup on, and a client that outlives the",
            "# terminal showing it is a client nobody can see or close.",
            "if [ ! -x \(ShellQuote.word(execPath)) ]; then",
            "\techo \(ShellQuote.word("devhub-terminal: \(execPath) is not there to run, so this window has no terminal session to attach to.")) >&2",
            "\texit 1",
            "fi",
            "devhub_argv=$(DEVHUB_CONTROL_SOCKET=\(ShellQuote.word(socketPath)) \\",
            "\(machineVariable)=\(ShellQuote.word(machine)) \\",
            "ELECTRON_RUN_AS_NODE=1 \\",
            "\(ShellQuote.word(execPath)) \(ShellQuote.word(entryScript)) \"$@\") || exit $?",
            "# An empty answer with a zero status is not an answer. Without this the",
            "# `exec` below would have no arguments, and a shell that execs nothing",
            "# carries on reading its input — which is a bare shell on the pty, the",
            "# one outcome this launcher exists to make impossible.",
            "if [ -z \"$devhub_argv\" ]; then",
            "\techo \"devhub-terminal: DevHub answered without a command line.\" >&2",
            "\texit 1",
            "fi",
            "eval \"exec $devhub_argv\"",
            "",
        ].joined(separator: "\n")
    }

    /// One shell word per argument, for the launcher to `exec`; the
    /// environment the command needs rides in the same line, through `env`.
    /// Nothing is prefixed when there is nothing to add.
    public static func commandLine(file: String, args: [String], env: [String: String] = [:]) -> String {
        let assignments = env.keys.sorted().map { "\($0)=\(env[$0]!)" }
        let argv = [file] + args
        return ShellQuote.argv(assignments.isEmpty ? argv : ["env"] + assignments + argv)
    }

    /// The `devhub` a pane on another machine runs (`remoteCliScript`).
    public static func remoteCliScript(execPath: String, cliScript: String, socketPath: String, machine: String) -> String {
        [
            "#!/bin/sh",
            "# Generated by DevHub on startup — do not edit, and do not copy.",
            "#",
            "# The paths below name one running DevHub, on the machine its window is",
            "# on, reached over a socket forwarded onto this one. They are rewritten",
            "# every time that DevHub starts.",
            "if [ ! -x \(ShellQuote.word(execPath)) ]; then",
            "\techo \(ShellQuote.word("devhub: \(execPath) is not there to run, so there is nothing here that can reach DevHub.")) >&2",
            "\texit 1",
            "fi",
            "DEVHUB_CONTROL_SOCKET=\(ShellQuote.word(socketPath)) \\",
            "DEVHUB_MACHINE=\(ShellQuote.word(machine)) \\",
            "exec \(ShellQuote.word(execPath)) \(ShellQuote.word(cliScript)) \"$@\"",
            "",
        ].joined(separator: "\n")
    }

    /// Where the launcher lives, given the user-data directory.
    public static func launcherPath(userDataPath: String) -> String {
        Path.join(userDataPath, "devhub", launcherName)
    }

    /// What the far machine's copy is filed under: a digest of this DevHub's
    /// control socket, so two profiles reaching one host do not collide.
    public static func remoteProfileTag(controlSocketPath: String) -> String {
        String(SHA256.hex(controlSocketPath).prefix(12))
    }

    /// The directory the `devhub` shim goes in on a machine DevHub is not
    /// running on — the whole directory goes on a pane's PATH.
    public static func remoteCliBinDirectory(home: String, controlSocketPath: String) -> String {
        Path.join(home, remoteDevhubDirectory, "\(remoteCliDirectoryPrefix)-\(remoteProfileTag(controlSocketPath: controlSocketPath))")
    }

    /// The directory a terminal belongs to, from what the launcher was started
    /// in. A cwd is always absolute; anything that is not is nil — the anchor's
    /// context — rather than a guess.
    public static func terminalRoot(_ directory: String?) -> String? {
        guard let directory, directory.hasPrefix("/") else { return nil }
        return directory
    }

    /// Which of these workspace roots contains `directory`, if any. The longest
    /// match wins, on whole path segments: `/work/app` does not contain
    /// `/work/app-old`.
    public static func enclosingRoot(_ roots: [String], _ directory: String?) -> String? {
        guard let directory else { return nil }
        var best: String?
        for root in roots where directory == root || directory.hasPrefix(root + "/") {
            if best == nil || root.utf16.count > best!.utf16.count { best = root }
        }
        return best
    }

    /// The Workspace a window named, when it named one: `--workspace <key>`.
    /// Anything else is a launcher this DevHub did not write, and is refused.
    public static func workspaceArgument(_ argv: [String]) throws -> String? {
        if argv.isEmpty { return nil }
        guard argv[0] == "--workspace", argv.count >= 2, !argv[1].isEmpty else {
            throw LauncherRefusal("devhub-terminal takes --workspace <key> and nothing else, and was given: \(argv.joined(separator: " "))")
        }
        if argv.count > 2 {
            throw LauncherRefusal("devhub-terminal takes one --workspace, and was given: \(argv.joined(separator: " "))")
        }
        return argv[1]
    }

    /// The sentences a launcher that cannot ask says (`resolveTerminalCommand`).
    public static func missingSocketMessage() -> String {
        "DEVHUB_CONTROL_SOCKET is not set, so this terminal cannot ask DevHub which session it belongs to. The launcher that sets it is written by DevHub on startup; a copy of it kept somewhere else is not one."
    }

    public static func missingMachineMessage() -> String {
        "\(machineVariable) is not set, so this terminal cannot tell DevHub which machine it is on — and a directory without a machine names a different folder on every one of them. The launcher that sets it is written by DevHub on startup; a copy of it kept somewhere else is not one."
    }

    public static func notListeningMessage(socketPath: String) -> String {
        "DevHub is not listening on \(socketPath), so this window has no terminal session to attach to."
    }
}

public struct LauncherRefusal: Error, Equatable, CustomStringConvertible {
    public let description: String
    init(_ description: String) { self.description = description }
}
