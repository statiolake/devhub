// Port of apps/desktop/src/main/cli/install.ts
//
// Putting `devhub` on the PATH (C-07).
//
// VS Code installs `code` by dropping a small shell script into a directory
// that is already on the PATH; this does the same thing for the same reason.
// The script is *generated* rather than symlinked because it is the one place
// the absolute facts a CLI cannot discover on its own are recorded: which
// socket the app it belongs to is listening on, which profile, and how to
// start that app when nothing is listening there.
//
// Consequence, and it is stated in the script itself: moving or reinstalling
// DevHub invalidates the launcher, and the command has to be run again.
//
// `sudo` is never used, and never offered. If `/usr/local/bin` is not
// writable the launcher goes to `~/.local/bin` and the person is told, in the
// same sentence, what to add to their PATH if it is not there already.
//
// The native script runs the bundle's own `devhub`
// (`DevHub.app/Contents/Resources/bin/devhub`) directly: there is no Electron
// to run a script with, so `ELECTRON_RUN_AS_NODE` is gone from it. The three
// variables it sets are the TypeScript launcher's, so either CLI reads either
// app's launcher.

import Foundation

public struct InstallRequest: Sendable {
    /// The `devhub` executable the launcher execs.
    public var executable: String
    /// The control socket of the app doing the installing.
    public var socketPath: String
    /// What the launcher is called (`devhub`, `devhub-dev`, …), and which
    /// DevHub it belongs to.
    public var commandName: String
    public var profile: String
    /// How to start this DevHub when nothing is listening on the socket.
    public var launchCommand: [String]
    public var home: String
    /// The PATH the installing process sees, for the "add this" advice.
    public var pathValue: String
    /// Overridden by the tests; production uses the two real candidates.
    public var candidates: [String]?

    public init(
        executable: String, socketPath: String, commandName: String, profile: String, launchCommand: [String],
        home: String, pathValue: String, candidates: [String]? = nil
    ) {
        self.executable = executable
        self.socketPath = socketPath
        self.commandName = commandName
        self.profile = profile
        self.launchCommand = launchCommand
        self.home = home
        self.pathValue = pathValue
        self.candidates = candidates
    }
}

public struct InstallResult: Equatable, Sendable {
    public var launcherPath: String
    public var message: String
}

public enum DevhubInstall {
    /// Quote a value for a POSIX shell, whatever is in it
    /// (`main/runtime/quote.ts`'s `shellQuote`; WP3's runtime has the shared one).
    public static func shellQuote(_ value: String) -> String {
        "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    /// A whole argv as one command line.
    public static func shellQuoteArgv(_ argv: [String]) -> String {
        argv.map(shellQuote).joined(separator: " ")
    }

    /// In order of preference: the shared one first, then the per-user one.
    public static func defaultCandidates(home: String) -> [String] {
        ["/usr/local/bin", Path.join(home, ".local", "bin")]
    }

    public static func launcherScript(_ request: InstallRequest) -> String {
        [
            "#!/bin/sh",
            "# Generated by DevHub — do not edit.",
            "#",
            "# Run the command \"DevHub: Install 'devhub' command in PATH\"",
            "# again after moving, updating or reinstalling DevHub: the paths below",
            "# are absolute, and that is what makes this script work from any shell.",
            "DEVHUB_CONTROL_SOCKET=\(shellQuote(request.socketPath)) \\",
            "DEVHUB_PROFILE=\(shellQuote(request.profile)) \\",
            "\(launchCommandEnvironmentVariable)=\(shellQuote(WireJSON.strings(request.launchCommand).compact)) \\",
            "exec \(shellQuote(request.executable)) \"$@\"",
            "",
        ].joined(separator: "\n")
    }

    static func isWritableDirectory(_ path: String) -> Bool {
        access(path, W_OK | X_OK) == 0
    }

    static func onPath(_ directory: String, _ pathValue: String) -> Bool {
        pathValue.split(separator: ":", omittingEmptySubsequences: false).contains { $0 == directory }
    }

    /// Write the launcher into the first candidate directory that will take
    /// it. Throws if none will: a command that reported success while having
    /// installed nothing is exactly the silent lie this does not permit.
    public static func installLauncher(_ request: InstallRequest) throws -> InstallResult {
        let candidates = request.candidates ?? defaultCandidates(home: request.home)
        var refused: [String] = []
        for directory in candidates {
            if !isWritableDirectory(directory) {
                // The per-user directory is ours to create; a system one is not.
                if directory.hasPrefix(request.home + "/") {
                    try FileManager.default.createDirectory(
                        atPath: directory, withIntermediateDirectories: true,
                        attributes: [.posixPermissions: 0o755])
                } else {
                    refused.append(directory)
                    continue
                }
            }
            let launcherPath = Path.join(directory, request.commandName)
            try Data(launcherScript(request).utf8).write(to: URL(fileURLWithPath: launcherPath))
            _ = chmod(launcherPath, 0o755)
            return InstallResult(
                launcherPath: launcherPath,
                message: installMessage(directory, launcherPath, refused, request))
        }
        throw DevhubFailure(
            "none of these directories would take the launcher: \(candidates.joined(separator: ", "))")
    }

    static func installMessage(_ directory: String, _ launcherPath: String, _ refused: [String], _ request: InstallRequest)
        -> String
    {
        var parts = ["Installed the '\(request.commandName)' command at \(launcherPath)."]
        if !refused.isEmpty {
            parts.append(
                "\(refused.joined(separator: " and ")) \(refused.count == 1 ? "is" : "are") not writable, so it was not used — DevHub does not use sudo."
            )
        }
        if !onPath(directory, request.pathValue) {
            parts.append(
                "\(directory) is not on your PATH. Add it, for example with: export PATH=\"\(directory):$PATH\"")
        }
        return parts.joined(separator: " ")
    }
}
