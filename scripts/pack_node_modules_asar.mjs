/*---------------------------------------------------------------------------------------------
 *  Collapse a packaged `node_modules` tree into `node_modules.asar` plus the
 *  `node_modules.asar.unpacked` sidecar, the way VS Code's own build does.
 *
 *  Why a Node script rather than Python: the archive format is written by the
 *  `@electron/asar` library, and the *header* has to record which entries live
 *  outside the archive. Splitting the tree by hand and packing what is left
 *  would produce an archive that reads correctly and resolves nothing — the
 *  unpacked entries would simply be absent from it.
 *
 *  Three sets, matching build/gulpfile.vscode.ts:
 *
 *    unpack     in the archive's header, contents on disk under
 *               `node_modules.asar.unpacked`. For everything that has to be a
 *               real file: native addons (`dlopen` needs a path), executables
 *               (`spawn` does not go through Electron's asar layer and fails
 *               with ENOTDIR inside one), and `.wasm`.
 *    skip       never enters the archive; stays a plain file in `node_modules`.
 *    duplicate  enters the archive *and* stays in `node_modules`, for code that
 *               is loaded by a plain Node subprocess with no resolution hook.
 *
 *  Usage: node pack_node_modules_asar.mjs <node_modules dir> <vscode dir>
 *---------------------------------------------------------------------------------------------*/

import { createRequire } from 'node:module';
import * as fs from 'node:fs';
import * as path from 'node:path';

const [, , nodeModulesDir, vscodeDir] = process.argv;
if (!nodeModulesDir || !vscodeDir) {
	console.error('usage: pack_node_modules_asar.mjs <node_modules dir> <vscode dir>');
	process.exit(2);
}

const require = createRequire(path.join(vscodeDir, 'build', 'x.js'));
const asar = require('@electron/asar');
const minimatch = createRequire(path.join(vscodeDir, 'x.js'))('minimatch');
const match = minimatch.minimatch ?? minimatch.default ?? minimatch;

// Kept in step with build/gulpfile.vscode.ts. Globs that match nothing are
// harmless: DevHub ships a subset of upstream's closure, and a list that still
// names the packages upstream names is the list a VS Code bump can be diffed
// against.
const UNPACK = [
	'**/*.node',
	'**/@vscode/ripgrep-universal/bin/**',
	'**/@github/copilot-{darwin,linux,linuxmusl,win32}-*/**',
	// The Dev Container CLI is spawned as an external Node process, so its
	// bundled entrypoint must be a real file rather than an archive member.
	'**/@devcontainers/cli/**',
	'**/@microsoft/mxc-sdk/bin/**',
	'**/node-pty/build/Release/*',
	'**/node-pty/build/Release/conpty/*',
	'**/node-pty/lib/worker/conoutSocketWorker.js',
	'**/node-pty/lib/shared/conout.js',
	'**/node-pty/package.json',
	'**/*.wasm',
	'**/@vscode/vsce-sign/bin/*',
];
const SKIP = ['**/*.mk'];
const DUPLICATE = [
	'vsda/**',
	'@vscode/sandbox-runtime/**',
	'@pondwader/socks5-server/**',
	'shell-quote/**',
	'zod/**',
];

const matchesAny = (relative, globs) => globs.some((glob) => match(relative, glob));

/** Every file under `dir`, as paths relative to it, following no symlinks. */
function walk(dir, prefix = '') {
	const found = [];
	for (const entry of fs.readdirSync(path.join(dir, prefix), { withFileTypes: true })) {
		const relative = prefix ? path.join(prefix, entry.name) : entry.name;
		if (entry.isDirectory()) {
			found.push(...walk(dir, relative));
		} else if (entry.isFile() || entry.isSymbolicLink()) {
			found.push(relative);
		}
	}
	return found;
}

const all = walk(nodeModulesDir);
const skipped = all.filter((f) => matchesAny(f, SKIP));
const duplicated = all.filter((f) => matchesAny(f, DUPLICATE));
const packed = all.filter((f) => !matchesAny(f, SKIP));
const unpacked = packed.filter((f) => matchesAny(f, UNPACK));

// `createPackageFromStreams` is the only entry point that takes the unpack
// decision as given. `createPackageFromFiles` looks like it should — it accepts
// a metadata record with an `unpack` field — but it ignores that field and
// re-derives the answer from a single `options.unpack` glob, matched against the
// *absolute* path. One glob cannot express the list below, so this builds the
// entry list itself and says `unpacked` outright, which is also what upstream's
// own `build/lib/asar.ts` does.
const directories = new Set();
for (const relative of packed) {
	for (let dir = path.dirname(relative); dir !== '.'; dir = path.dirname(dir)) {
		directories.add(dir);
	}
}

const entries = [...directories].sort().map((relative) => ({
	path: relative,
	type: 'directory',
	unpacked: false,
	stat: fs.lstatSync(path.join(nodeModulesDir, relative)),
}));
for (const relative of packed.sort()) {
	const absolute = path.join(nodeModulesDir, relative);
	const stat = fs.lstatSync(absolute);
	const unpack = matchesAny(relative, UNPACK);
	if (stat.isSymbolicLink()) {
		entries.push({
			path: relative,
			type: 'link',
			unpacked: unpack,
			stat,
			symlink: fs.readlinkSync(absolute),
			streamGenerator: () => fs.createReadStream(absolute),
		});
		continue;
	}
	entries.push({
		path: relative,
		type: 'file',
		unpacked: unpack,
		stat,
		streamGenerator: () => fs.createReadStream(absolute),
	});
}

const archive = path.join(path.dirname(nodeModulesDir), 'node_modules.asar');
await asar.createPackageFromStreams(archive, entries);

// What is left in `node_modules` is only what was never meant to be collapsed.
// Removing the rest is the whole point: a tree that is both archived and
// present on disk is the file count this change exists to remove.
const keep = new Set([...skipped, ...duplicated]);
for (const relative of all) {
	if (!keep.has(relative)) {
		fs.rmSync(path.join(nodeModulesDir, relative), { force: true });
	}
}
// Prune the directories the removals emptied, deepest first.
for (const dir of [...directories].sort((a, b) => b.length - a.length)) {
	const absolute = path.join(nodeModulesDir, dir);
	if (fs.existsSync(absolute) && fs.readdirSync(absolute).length === 0) {
		fs.rmdirSync(absolute);
	}
}
if (fs.existsSync(nodeModulesDir) && fs.readdirSync(nodeModulesDir).length === 0) {
	fs.rmdirSync(nodeModulesDir);
}

console.log(
	`    ${packed.length} files archived, ${unpacked.length} unpacked, ` +
	`${keep.size} left in node_modules`
);
